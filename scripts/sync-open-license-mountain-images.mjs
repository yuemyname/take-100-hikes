async function fetchWithRetry(url) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const response = await fetch(url, {
      headers: { 'User-Agent': '100PEAKS-mountain-photo-sync/0.1' },
    });
    if (response.ok) return response;
    if (response.status !== 429 && response.status < 500) {
      throw new Error(`Open-license source returned ${response.status} ${response.statusText}: ${url}`);
    }
    await new Promise((resolve) => setTimeout(resolve, 1000 * (2 ** attempt)));
  }
  throw new Error(`Open-license source did not recover after retries: ${url}`);
}

async function readSource(url, useSystemCurl = false) {
  if (useSystemCurl) {
    return execFileSync('curl', ['-L', '-sS', '--fail', url], {
      maxBuffer: 20 * 1024 * 1024,
    });
  }
  const response = await fetchWithRetry(url);
  return Buffer.from(await response.arrayBuffer());
}

function maybeGunzip(bytes) {
  return bytes[0] === 0x1f && bytes[1] === 0x8b ? gunzipSync(bytes) : bytes;
}

function assertJpeg(bytes, slug) {
  if (bytes[0] !== 0xff || bytes[1] !== 0xd8) {
    throw new Error(`${slug} did not return a JPEG image.`);
  }
}

function createGeneratedModule(records) {
  const entries = records.map((record) => `  ${JSON.stringify(record.slug)}: {
    source: require(${JSON.stringify(`../../assets/photos/open-license-mountains/${record.slug}.jpg`)}),
    author: ${JSON.stringify(record.author)},
    license: ${JSON.stringify(record.license)},
    licenseUrl: ${JSON.stringify(record.licenseUrl)},
    sourceUrl: ${JSON.stringify(record.imageUrl)},
    articleUrl: ${JSON.stringify(record.articleUrl)},
  },`).join('\n');
  return `// Generated by scripts/sync-open-license-mountain-images.mjs. Do not edit by hand.
export const OPEN_LICENSE_MOUNTAIN_IMAGES = {
${entries}
} as const;
`;
}

const mountains = JSON.parse(await readFile(mountainsPath, 'utf8'));
const mountainBySlug = new Map(mountains.map((mountain) => [mountain.slug, mountain]));
const outputDirectory = shouldWrite ? photoDirectory : previewDirectory;
await mkdir(outputDirectory, { recursive: true });

const records = [];
for (const reviewed of reviewedRecords) {
  const mountain = mountainBySlug.get(reviewed.slug);
  if (!mountain) throw new Error(`Unknown mountain slug: ${reviewed.slug}`);
  const repositoryArea = mountain.area ?? mountain.region;
  if (!repositoryArea.includes(reviewed.areaGuard)) {
    throw new Error(`${mountain.name_ko} area no longer contains ${reviewed.areaGuard}: ${repositoryArea}`);
  }

  const evidence = (await readSource(reviewed.evidenceUrl, reviewed.useSystemCurl)).toString('utf8');
  for (const expected of reviewed.evidenceChecks) {
    if (!evidence.includes(expected)) {
      throw new Error(`${mountain.name_ko} evidence no longer contains ${expected}.`);
    }
  }

  const bytes = maybeGunzip(await readSource(reviewed.imageUrl, reviewed.useSystemCurl));
  assertJpeg(bytes, reviewed.slug);
  await writeFile(join(outputDirectory, `${reviewed.slug}.jpg`), bytes);
  const publicRecord = { ...reviewed };
  delete publicRecord.useSystemCurl;
  records.push({
    ...publicRecord,
    mountainName: mountain.name_ko,
    repositoryArea,
    provider: '공공저작물',
    gpsCoordinateChanged: false,
  });
}

const expectedFiles = new Set(records.map((record) => `${record.slug}.jpg`));
for (const file of await readdir(outputDirectory)) {
  if (/\.jpe?g$/i.test(file) && !expectedFiles.has(file)) await unlink(join(outputDirectory, file));
}

if (shouldWrite) {
  await writeFile(auditPath, `${JSON.stringify({
    generatedAt: new Date().toISOString(),
    sourcePolicy: 'Only visually reviewed, exact mountain-and-region matches with an explicit public or Creative Commons reuse license are bundled.',
    gpsPolicy: 'Photo sources and their page coordinates are never copied into GPS verification fields.',
    records,
  }, null, 2)}\n`);
  await writeFile(generatedPath, createGeneratedModule(records));
  console.log(`Wrote ${records.length} open-license mountain photos.`);
} else {
  await writeFile(join(previewDirectory, 'manifest.json'), `${JSON.stringify(records, null, 2)}\n`);
  console.log(`Downloaded ${records.length} open-license preview photos to ${previewDirectory}.`);
}
